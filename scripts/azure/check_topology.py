#!/usr/bin/env python3
"""Validate isolation/security properties of the actual compiled ARM templates."""
import json
from pathlib import Path

root=Path(__file__).resolve().parents[2]
bootstrap=json.loads((root/'artifacts/infra/bootstrap.json').read_text())
main=json.loads((root/'artifacts/infra/main.json').read_text())
expected=json.loads((root/'infra/azure/environments.json').read_text())
assert bootstrap['variables']['$fxv#0']==expected
assert main['variables']['$fxv#0']==expected
resources=bootstrap['resources']
groups=[r for r in resources if r['type']=='Microsoft.Resources/resourceGroups']
assert len(groups)==1 and groups[0]['copy']['count']=="[length(variables('environments'))]", 'Only the two environment RGs may be created.'
identity=next(r for r in resources if r['type']=='Microsoft.Resources/deployments' and r['name'].startswith("[format('identity-"))
role=next(r for r in resources if r['type']=='Microsoft.Resources/deployments' and r['name'].startswith("[format('role-"))
assert identity['resourceGroup']==role['resourceGroup']==groups[0]['name'], 'Identity/RBAC must be scoped to its own environment RG.'
assert identity['properties']['parameters']['name']['value'].endswith('.identityName]')
assert identity['properties']['parameters']['location']['value']==groups[0]['location']
assert identity['properties']['parameters']['oidcSubjectPrefix']['value']=="[parameters('oidcSubjectPrefix')]"
federation=next(r for r in identity['properties']['template']['resources'] if r['type'].endswith('/federatedIdentityCredentials'))
assert federation['properties']=={
    'issuer':'https://token.actions.githubusercontent.com',
    'subject':"[format('{0}:environment:{1}', parameters('oidcSubjectPrefix'), parameters('environment'))]",
    'audiences':['api://AzureADTokenExchange'],
}, 'Federation must preserve the exact discovered prefix and isolate each environment.'
assert identity['properties']['parameters']['environment']['value']=="[variables('environments')[copyIndex()]]"
roles=role['properties']['template']['resources']
definition=next(r for r in roles if r['type']=='Microsoft.Authorization/roleDefinitions')['properties']
assert definition['assignableScopes']==['[resourceGroup().id]']
actions=definition['permissions'][0]['actions']
assert set(actions)=={
    'Microsoft.Resources/subscriptions/resourceGroups/read','Microsoft.Resources/deployments/*',
    'Microsoft.Web/serverfarms/*','Microsoft.Web/sites/*','Microsoft.Insights/components/*',
    'Microsoft.OperationalInsights/workspaces/*',
}, 'CI must not acquire identity, federation, RBAC or arbitrary-resource permissions.'
app=next(r for r in main['resources'] if r['name']=='app-service')
connection=app['properties']['parameters']['monitoringConnection']
assert connection.startswith("[if(parameters('reconcileMonitoring'), ")
assert "'monitoring')" in connection and '.outputs.connectionString.value' in connection, 'Provisioning must consume the completed monitoring module output.'
assert connection.index('.outputs.connectionString.value') < connection.index('.ConnectionString'), 'Only activation may read an existing Insights component.'
assert any("'monitoring')" in dependency for dependency in app['dependsOn']), 'ARM must wait for monitoring creation.'
site=next(r for r in app['properties']['template']['resources'] if r['type']=='Microsoft.Web/sites')
assert site['properties']['siteConfig']['use32BitWorkerProcess'] is True, 'F1 rejects a 64-bit worker request at creation.'
assert site['properties']['siteConfig']['alwaysOn'] is False
assert site['properties']['siteConfig']['linuxFxVersion']=='DOTNETCORE|10.0'
assert 'autoGeneratedDomainNameLabelScope' not in site['properties'], 'Do not opt into a hashed hostname.'
assert app['properties']['parameters']['name']['value']=="[variables('configuration').appName]"
assert app['properties']['parameters']['planName']['value']=="[variables('configuration').planName]"
probe=json.loads((root/'artifacts/infra/f1-quota-probe.json').read_text())
assert len(probe['resources'])==1
plan=probe['resources'][0]
assert plan['type']=='Microsoft.Web/serverfarms' and plan['sku']=={'name':'F1','tier':'Free','capacity':1}
assert plan['properties']['reserved'] is True
assert set(probe['parameters'])=={'planName','location'}
print('Compiled topology: exact names/regions, two RGs, in-group identities, restricted CI role and classic hostname request verified.')
