test('clipboard denial reports the real failure and preserves native editor text and selection', async ({ workspace: { page, context } }) => {
  await openWorkspace(page, 'translate'); await page.getByLabel('Source text', { exact: true }).fill('Keep this selection.\nSecond line.')
  const source = page.getByRole('textbox', { name: 'Source text', exact: true })
  await source.focus(); await source.evaluate(element => (element as HTMLTextAreaElement).setSelectionRange(5, 9))
  const cdp = await context.newCDPSession(page)
  const target = await cdp.send('Target.getTargetInfo')
  await cdp.send('Browser.setPermission', { browserContextId: target.targetInfo.browserContextId, permission: { name: 'clipboard-write' }, setting: 'denied', origin: new URL(page.url()).origin })
  await page.getByRole('button', { name: 'Copy source text' }).click()
  await expect(page.getByText('Couldn’t copy. Select the text and copy it manually.')).toBeVisible()
  await expect(source).toHaveValue('Keep this selection.\nSecond line.')
  expect(await source.evaluate(element => [(element as HTMLTextAreaElement).selectionStart, (element as HTMLTextAreaElement).selectionEnd])).toEqual([5, 9])
})

test('unknown alternatives use the original identity and never regenerate after real network interruption', async ({ workspace: { page, context } }) => {
  test.setTimeout(30000)
  await page.clock.install()
  await page.clock.pauseAt(new Date(Date.now() + 1000))
  const alternatives: Record<string, unknown>[] = []
  page.on('request', request => { if (new URL(request.url()).pathname === '/api/rewriting/alternatives') alternatives.push(request.postDataJSON() as Record<string, unknown>) })
  await openWorkspace(page, 'rewrite'); await page.getByLabel('Source text', { exact: true }).fill('M045-DELAY-ALTERNATIVES')
  await page.clock.runFor(1000); await expectResult(page, 'rewrite', 'M039-DELAY. The report is ready.')
  await page.getByRole('button', { name: 'Sentence alternatives: The report is ready.' }).click()
  await expect.poll(() => alternatives.length).toBe(1)
  const identity = String(alternatives[0].operationId)
  await expect.poll(async () => { const response = await page.request.get(`/api/operations/${identity}`); return response.status() === 200 ? (await response.json()).status : 'absent' }, { intervals: [10, 20, 50] }).toBe('pending')
  await context.setOffline(true); await page.clock.runFor(15000)
  await expect(page.getByRole('button', { name: 'Check status' })).toBeVisible()
  await context.setOffline(false)
  const checked = page.waitForResponse(response => new URL(response.url()).pathname === `/api/operations/${identity}`)
  await page.getByRole('button', { name: 'Check status' }).click()
  const metadata = await (await checked).json()
  expect(metadata).toMatchObject({ kind: 'sentenceAlternatives', outputAvailable: false })
  expect(metadata.options).toBeUndefined()
  await page.clock.runFor(2000)
  expect(alternatives).toHaveLength(1)
  await expectResult(page, 'rewrite', 'M039-DELAY. The report is ready.')
})
