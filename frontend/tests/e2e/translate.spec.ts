test('Translation pauses once, returns editable output and supports native copy without another charge', async ({ workspace: { page } }) => {
  const posts = trackOperations(page)
  await openWorkspace(page, 'translate')
  await page.getByLabel('Source language').selectOption('en')
  await page.getByLabel('Target language').selectOption('ro')
  const before = await usage(page)
  await page.getByLabel('Source text', { exact: true }).fill(TRANSLATE_SOURCE)
  await expect(page.getByRole('textbox', { name: 'Translation result' })).toHaveValue(TRANSLATE_RESULT)
  expect(posts).toHaveLength(1)
  expect(posts[0]).toMatchObject({ source: TRANSLATE_SOURCE, family: 'translation' })
  expect((await usage(page)).consumedCharacters).toBe(before.consumedCharacters + 46)
  await nativeCopy(page, 'Translation result', `${TRANSLATE_RESULT} Edited.\nSecond line.`)
  expect(posts).toHaveLength(1)
  expect((await usage(page)).consumedCharacters).toBe(before.consumedCharacters + 46)
  await page.getByRole('button', { name: 'Clear source text' }).click()
  await expect(page.getByLabel('Source text', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Source text', { exact: true })).toBeFocused()
  await expect(page.getByRole('textbox', { name: 'Translation result' })).toHaveValue(`${TRANSLATE_RESULT} Edited.\nSecond line.`)
  for (const name of ['Translate', 'Rewrite', 'Start new workspace', 'Refresh usage']) await expect(page.getByRole('button', { name, exact: true })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Usage' })).toHaveCount(0)
})

test('Translation blocks the entire oversized input without an operation or charge', async ({ workspace: { page } }) => {
  const posts = trackOperations(page)
  await openWorkspace(page, 'translate')
  const before = await usage(page)
  await page.getByLabel('Source text', { exact: true }).fill('a'.repeat(5001))
  await expect(page.getByRole('alert')).toContainText('Translation is limited to 5,000 characters. Shorten the text to continue.')
  await expect(page.getByLabel('Source text', { exact: true })).toHaveValue('a'.repeat(5001))
  expect(posts).toHaveLength(0)
  expect((await usage(page)).consumedCharacters).toBe(before.consumedCharacters)
})

