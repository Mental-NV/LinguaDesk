test('Translation definitive failure offers one explicit retry with a new identity', async ({ workspace: { page } }) => {
  const posts = trackOperations(page)
  await openWorkspace(page, 'translate')
  await page.getByLabel('Source language').selectOption('en')
  await page.getByLabel('Target language').selectOption('ro')
  await page.getByLabel('Source text', { exact: true }).fill(TRANSLATE_SOURCE)
  await expect(page.getByRole('textbox', { name: 'Translation result' })).toHaveValue(TRANSLATE_RESULT)
  const before = await usage(page)
  await page.getByLabel('Source text', { exact: true }).fill(`${TRANSLATE_SOURCE} M028-PROCESSING-FAILURE`)
  await expect(page.getByRole('alert')).toContainText('We couldn’t process this text.')
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect.poll(() => posts.length).toBe(3)
  await expect(page.getByRole('alert')).toContainText('We couldn’t process this text.')
  expect(posts[1].operationId).not.toBe(posts[2].operationId)
  await expect(page.getByRole('textbox', { name: 'Translation result' })).toHaveValue(TRANSLATE_RESULT)
  expect((await usage(page)).consumedCharacters).toBe(before.consumedCharacters)
})

test('Translation retains an invalid target until corrected', async ({ workspace: { page } }) => {
  const posts = trackOperations(page)
  await openWorkspace(page, 'translate')
  await page.getByLabel('Target language').selectOption('ro')
  await page.getByLabel('Source language').selectOption('ro')
  await page.getByLabel('Source text', { exact: true }).fill(TRANSLATE_SOURCE)
  await expect(page.getByRole('alert')).toContainText('Choose a target language different from Romanian.')
  await expect(page.getByLabel('Target language')).toHaveValue('ro')
  expect(posts).toHaveLength(0)
  await page.getByLabel('Source language').selectOption('en')
  await expect(page.getByRole('textbox', { name: 'Translation result' })).toHaveValue(TRANSLATE_RESULT)
})
