test('Rewriting pauses once, returns editable output and supports native copy without another charge', async ({ workspace: { page } }) => {
  const posts = trackOperations(page)
  await openWorkspace(page, 'rewrite')
  await page.getByLabel('Writing language').selectOption('en')
  const before = await usage(page)
  await page.getByLabel('Source text', { exact: true }).fill(REWRITE_SOURCE)
  await expectResult(page, 'rewrite', REWRITE_RESULT)
  expect(posts).toHaveLength(1)
  expect(posts[0]).toMatchObject({ source: REWRITE_SOURCE, family: 'rewriting' })
  expect((await usage(page)).consumedCharacters).toBe(before.consumedCharacters + 46)
  await nativeCopy(page, 'Improved result', `${REWRITE_RESULT} Edited.\nSecond line.`)
  expect(posts).toHaveLength(1)
  expect((await usage(page)).consumedCharacters).toBe(before.consumedCharacters + 46)
  await page.getByRole('button', { name: 'Clear source text' }).click()
  await expect(page.getByLabel('Source text', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Source text', { exact: true })).toBeFocused()
  await expectResult(page, 'rewrite', `${REWRITE_RESULT} Edited.\nSecond line.`)
  for (const name of ['Translate', 'Rewrite', 'Start new workspace', 'Refresh usage']) await expect(page.getByRole('button', { name, exact: true })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Usage' })).toHaveCount(0)
})

test('Rewriting blocks the entire oversized input without an operation or charge', async ({ workspace: { page } }) => {
  const posts = trackOperations(page)
  await openWorkspace(page, 'rewrite')
  const before = await usage(page)
  await page.getByLabel('Source text', { exact: true }).fill('a'.repeat(2001))
  await expect(page.getByRole('alert')).toContainText('Rewriting is limited to 2,000 characters. Shorten the text to continue.')
  await expect(page.getByLabel('Source text', { exact: true })).toHaveValue('a'.repeat(2001))
  expect(posts).toHaveLength(0)
  expect((await usage(page)).consumedCharacters).toBe(before.consumedCharacters)
})

