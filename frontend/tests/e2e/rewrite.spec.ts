test('Rewriting definitive failure offers one explicit retry with a new identity', async ({ workspace: { page } }) => {
  const posts = trackOperations(page)
  await openWorkspace(page, 'rewrite')
  await page.getByLabel('Writing language').selectOption('en')
  await page.getByLabel('Source text', { exact: true }).fill(REWRITE_SOURCE)
  await expectResult(page, 'rewrite', REWRITE_RESULT)
  const before = await usage(page)
  await page.getByLabel('Source text', { exact: true }).fill(`${REWRITE_SOURCE} M029-PROCESSING-FAILURE`)
  await expect(page.getByRole('alert')).toContainText('We couldn’t process this text.')
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect.poll(() => posts.length).toBe(3)
  await expect(page.getByRole('alert')).toContainText('We couldn’t process this text.')
  expect(posts[1].operationId).not.toBe(posts[2].operationId)
  await expectResult(page, 'rewrite', REWRITE_RESULT)
  expect((await usage(page)).consumedCharacters).toBe(before.consumedCharacters)
})

test('Rewriting exposes one mode selector and submits only its final native selection', async ({ workspace: { page } }) => {
  const posts = trackOperations(page)
  await openWorkspace(page, 'rewrite')
  await page.getByRole('button', { name: 'Toolbar', exact: true }).click()
  await expect(page.getByRole('switch', { name: 'Correction Only' })).toBeChecked()
  await page.getByRole('switch', { name: 'Correction Only' }).click()
  await page.getByRole('button', { name: 'Styles/Tones', exact: true }).click()
  await expect(page.getByRole('listbox').getByRole('option')).toHaveCount(9)
  await page.keyboard.press('Escape')
  await page.getByLabel('Source text', { exact: true }).fill(REWRITE_SOURCE)
  await chooseMode(page, 'business')
  await chooseMode(page, 'friendly')
  await expectResult(page, 'rewrite', REWRITE_RESULT)
  expect(posts).toHaveLength(1)
  expect(posts[0].mode).toBe('friendly')
})
