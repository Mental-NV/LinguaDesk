import { act, cleanup, fireEvent, screen } from '@testing-library/react'
import { expectResult, advance, deferred, editSource, flush, FIXED_TIME, installWorkspaceFetch, json, mountWorkspace, RESULT, selectValid, USAGE } from '../helpers/workspace'

beforeEach(() => { vi.useFakeTimers(); vi.setSystemTime(new Date(FIXED_TIME)); vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(true) })
afterEach(() => { cleanup(); vi.useRealTimers(); vi.unstubAllGlobals() })
it('SPA navigation cancels queued work, preserves both pages and never restarts on return', async () => {
  const network = installWorkspaceFetch()
  const view = mountWorkspace('translation'); await flush(); selectValid('translation'); editSource('Translation draft')
  await advance(500)
  view.navigate('rewriting'); await flush(); selectValid('rewriting'); editSource('Rewriting draft')
  await advance(500)
  view.navigate('translation'); await advance(2000)
  expect(screen.getByLabelText('Source text')).toHaveValue('Translation draft')
  expect(network.operations).toHaveLength(0)
  view.navigate('rewriting')
  expect(screen.getByLabelText('Source text')).toHaveValue('Rewriting draft')
})
it('a hidden submitted operation settles in its own page and shares ordered usage without moving focus', async () => {
  const pending = deferred<Response>()
  const network = installWorkspaceFetch({ operation: () => pending.promise })
  const view = mountWorkspace('translation'); await flush(); selectValid('translation'); editSource(); await advance()
  view.navigate('rewriting'); await flush()
  screen.getByLabelText('Source text').focus()
  await act(async () => pending.resolve(json({ translatedText: RESULT, characterCount: 46, admissionDay: USAGE.day, usage: { ...USAGE, consumedCharacters: 7546, availableCharacters: 12454, revision: 2 } })))
  expect(screen.getByLabelText('Source text')).toHaveFocus()
  expectResult('rewriting', '')
  expect(view.stores().rewrite.state.usage?.consumedCharacters).toBe(7546)
  view.navigate('translation')
  expect(screen.getByLabelText('Translation result')).toHaveValue(RESULT)
  expect(network.operations).toHaveLength(1)
})
it.each(['pagehide', 'pageshow'])('%s teardown clears both stores and fences pending callbacks', async event => {
  const pending = deferred<Response>()
  installWorkspaceFetch({ operation: () => pending.promise })
  const view = mountWorkspace('translation'); await flush(); selectValid('translation'); editSource(); await advance()
  const restoration = new Event(event)
  if (event === 'pageshow') Object.defineProperty(restoration, 'persisted', { value: true })
  fireEvent(window, restoration)
  expect(view.stores().translate.state.source).toBe('')
  expect(view.stores().rewrite.state.source).toBe('')
  expect(view.stores().translate.state.usage).toBe(null)
  await act(async () => pending.resolve(json({ translatedText: 'Late private text', admissionDay: USAGE.day, characterCount: 46, usage: USAGE })))
  await advance(3000)
  expect(screen.getByLabelText('Translation result')).toHaveValue('')
  // Synthetic events verify handlers, not actual browser restoration.
})
it('resetAll cancels both timers and clears account availability before any new session', async () => {
  const network = installWorkspaceFetch()
  const view = mountWorkspace('translation'); await flush(); selectValid('translation'); editSource()
  act(() => view.stores().resetAll())
  await advance(2000)
  expect(network.operations).toHaveLength(0)
  expect(view.stores().translate.state).toMatchObject({ source: '', target: '', mode: 'correctionOnly', usage: null })
})
