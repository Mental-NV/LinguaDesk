import { act, cleanup, fireEvent, screen, within } from '@testing-library/react'
import { chooseMode, expectResult, resultEditor, advance, CAPABILITIES, deferred, editSource, flush, FIXED_TIME, installWorkspaceFetch, json, MODES, mountWorkspace, RESULT, resultName, selectValid, SOURCE, USAGE } from '../helpers/workspace'
import { MESSAGE_UNKNOWN_OUTCOME } from '../../src/shell/workspaceModel'

beforeEach(() => {
  vi.useFakeTimers()
  vi.setSystemTime(new Date(FIXED_TIME))
  vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(true)
})
afterEach(() => { cleanup(); vi.useRealTimers(); vi.unstubAllGlobals() })

for (const feature of ['translation', 'rewriting'] as const) {
  describe(`${feature} paused workspace`, () => {
    async function ready(options: Parameters<typeof installWorkspaceFetch>[0] = {}) {
      const network = installWorkspaceFetch(options)
      const view = mountWorkspace(feature)
      await flush()
      selectValid(feature)
      return { ...network, ...view }
    }
    it('always renders labelled plain editors, native selectors and no retired controls', async () => {
      await ready()
      if (feature === 'translation') expect(screen.getByRole('textbox', { name: resultName(feature) })).toHaveAttribute('readonly')
      else expectResult(feature, '')
      expect(screen.getAllByRole('heading', { level: 2 })).toHaveLength(2)
      for (const name of ['Translate', 'Rewrite', 'Copy result', 'Start new workspace', 'Refresh usage']) expect(screen.queryByRole('button', { name })).not.toBeInTheDocument()
      expect(screen.queryByRole('region', { name: 'Usage' })).not.toBeInTheDocument()
      expect(screen.queryByText(/characters used|characters remaining|Ready to process/)).not.toBeInTheDocument()
      expect(screen.getByLabelText('Source text')).toHaveAttribute('autocomplete', 'off')
      if (feature === 'translation') expect(resultEditor(feature)).toHaveAttribute('autocomplete', 'off')
    })
    it('does not dispatch at 999 ms and dispatches once at 1000 ms without repeating', async () => {
      const h = await ready()
      editSource()
      await advance(999)
      expect(h.operations).toHaveLength(0)
      await advance(1)
      expect(h.operations).toHaveLength(1)
      expect(h.operations[0]).toMatchObject({ family: feature, source: SOURCE, sourceSelection: 'en' })
      expectResult(feature, RESULT)
      expect(resultEditor(feature)).not.toHaveAttribute('readonly')
      await advance(5000)
      expect(h.operations).toHaveLength(1)
    })
    it('restarts the pause on text and selector changes and captures only the latest values', async () => {
      const h = await ready()
      editSource('First source.')
      await advance(700)
      editSource('Latest source.')
      await advance(700)
      if (feature === 'translation') fireEvent.change(screen.getByLabelText('Target language'), { target: { value: 'ru' } })
      else chooseMode('friendly')
      await advance(999)
      expect(h.operations).toHaveLength(0)
      await advance(1)
      expect(h.operations).toHaveLength(1)
      expect(h.operations[0]).toMatchObject({ source: 'Latest source.', [feature === 'translation' ? 'target' : 'mode']: feature === 'translation' ? 'ru' : 'friendly' })
    })
    it('keeps empty, whitespace and oversized inputs unsubmitted while retaining every character', async () => {
      const h = await ready()
      for (const input of ['', ' \n\t', 'a'.repeat(feature === 'translation' ? 5001 : 2001)]) {
        editSource(input)
        await advance(2000)
        expect(h.operations).toHaveLength(0)
        expect(screen.getByLabelText('Source text')).toHaveValue(input)
      }
      expect(screen.getByRole('alert')).toHaveTextContent('Shorten the text to continue.')
      editSource('Valid again.')
      await advance()
      expect(h.operations).toHaveLength(1)
    })
    it('suppresses interim composition and starts a fresh pause on compositionend', async () => {
      const h = await ready()
      editSource()
      await advance(500)
      fireEvent.compositionStart(screen.getByLabelText('Source text'))
      editSource('你好世界')
      await advance(3000)
      expect(h.operations).toHaveLength(0)
      fireEvent.compositionEnd(screen.getByLabelText('Source text'))
      await advance(999)
      expect(h.operations).toHaveLength(0)
      await advance(1)
      expect(h.operations).toHaveLength(1)
      expect(h.operations[0].source).toBe('你好世界')
    })
    it('queues only the latest paused source until the previous operation settles', async () => {
      const pending = deferred<Response>()
      const h = await ready({ operation: (body, index) => index === 1 ? pending.promise : json({ translatedText: 'Latest output', rewrittenText: 'Latest output', admissionDay: USAGE.day, characterCount: [...body.source].length, usage: { ...USAGE, revision: 3 } }) })
      editSource('First.')
      await advance()
      editSource('Second.')
      await advance()
      editSource('Third.')
      await advance()
      expect(h.operations).toHaveLength(1)
      await act(async () => pending.resolve(json({ translatedText: 'Old output', rewrittenText: 'Old output', admissionDay: USAGE.day, characterCount: 6, usage: { ...USAGE, revision: 2 } })))
      await flush()
      expect(h.operations).toHaveLength(2)
      expect(h.operations[1].source).toBe('Third.')
      expectResult(feature, 'Latest output')
      expect(screen.getByLabelText('Source text')).toHaveValue('Third.')
    })
    it('rejects a pending result after a source edit even before the new pause expires', async () => {
      const pending = deferred<Response>()
      const h = await ready({ operation: () => pending.promise })
      editSource()
      await advance()
      editSource('Updated.')
      await act(async () => pending.resolve(json({ translatedText: 'Old', rewrittenText: 'Old', admissionDay: '2026-10-24', characterCount: 46, usage: { ...USAGE, revision: 2 } })))
      await flush()
      expectResult(feature, '')
      expect(screen.getByText(/46 characters counted toward your usage/)).toHaveTextContent('2026-10-24')
      expect(h.operations).toHaveLength(1)
    })
    it('keeps previous output editable during an update; editing cancels the queued candidate and protects the edit', async () => {
      const pending = deferred<Response>()
      const h = await ready({ operation: (body, index) => index === 1 ? json({ translatedText: RESULT, rewrittenText: RESULT, admissionDay: USAGE.day, characterCount: 46, usage: { ...USAGE, revision: 2 } }) : index === 2 ? pending.promise : json({ translatedText: 'New result', rewrittenText: 'New result', admissionDay: USAGE.day, characterCount: 3, usage: { ...USAGE, revision: 4 } }) })
      editSource()
      await advance()
      editSource('Update.')
      await advance()
      expectResult(feature, RESULT)
      expect(resultEditor(feature)).toHaveAttribute('aria-busy', 'true')
      editSource('Queued.')
      await advance()
      fireEvent.change(resultEditor(feature), { target: { value: 'My edit\nSecond line' } })
      await act(async () => pending.resolve(json({ translatedText: 'Old', rewrittenText: 'Old', admissionDay: USAGE.day, characterCount: 7, usage: { ...USAGE, revision: 3 } })))
      await advance(3000)
      expect(h.operations).toHaveLength(2)
      expectResult(feature, 'My edit\nSecond line')
      editSource('New')
      await advance()
      expect(h.operations).toHaveLength(3)
      expectResult(feature, 'New result')
    })
    it('compositionstart protects pending output even when result composition is cancelled', async () => {
      const pending = deferred<Response>()
      const h = await ready({ operation: (body, index) => index === 1 ? json({ translatedText: RESULT, rewrittenText: RESULT, admissionDay: USAGE.day, characterCount: 46, usage: { ...USAGE, revision: 2 } }) : pending.promise })
      editSource(); await advance()
      editSource('Updated'); await advance()
      fireEvent.compositionStart(resultEditor(feature))
      fireEvent.compositionEnd(resultEditor(feature))
      await act(async () => pending.resolve(json({ translatedText: 'Old', rewrittenText: 'Old', admissionDay: USAGE.day, characterCount: 7, usage: { ...USAGE, revision: 3 } })))
      await advance(2000)
      expect(h.operations).toHaveLength(2)
      expectResult(feature, RESULT)
    })
    it('Clear source text preserves the result and focus and cancels the pause', async () => {
      const h = await ready()
      editSource(); await advance()
      editSource('Queued')
      fireEvent.click(screen.getByRole('button', { name: 'Clear source text' }))
      await advance(2000)
      expect(h.operations).toHaveLength(1)
      expect(screen.getByLabelText('Source text')).toHaveValue('')
      expect(screen.getByLabelText('Source text')).toHaveFocus()
      expectResult(feature, RESULT)
    })
    it('cancels a preflight when edited and never posts its obsolete payload', async () => {
      const token = deferred<Response>()
      let calls = 0
      const h = await ready({ bootstrap: () => ++calls === 1 ? token.promise : json({ requestToken: 'token' }) })
      editSource(); await advance()
      editSource('Latest')
      await act(async () => token.resolve(json({ requestToken: 'token' })))
      await advance(999)
      expect(h.operations).toHaveLength(0)
      await advance(1)
      expect(h.operations).toHaveLength(1)
      expect(h.operations[0].source).toBe('Latest')
    })
    it('keeps definitive failures settled without retry loops and explicit retry uses a new identity', async () => {
      const h = await ready({ operation: () => json({ category: 'processingFailure' }, 502) })
      editSource(); await advance()
      expect(screen.getByRole('alert')).toHaveTextContent('We couldn’t process this text.')
      await advance(5000)
      expect(h.operations).toHaveLength(1)
      fireEvent.click(screen.getByRole('button', { name: 'Try again' }))
      await flush()
      expect(h.operations).toHaveLength(2)
      expect(h.operations[1].operationId).not.toBe(h.operations[0].operationId)
    })
    it('retains an unknown operation across edits and only status terminality releases queued work', async () => {
      let terminal = false
      const h = await ready({ operation: () => Promise.reject(new TypeError('offline')), status: () => terminal ? json({ status: 'failed', characterCount: 0, admissionDay: USAGE.day, usage: USAGE }) : json({}, 404) })
      editSource(); await advance()
      expect(screen.getByRole('alert')).toHaveTextContent(MESSAGE_UNKNOWN_OUTCOME)
      const original = h.state().pendingOperationId
      editSource('Queued newer source')
      await advance(3000)
      expect(h.operations).toHaveLength(1)
      expect(h.state().pendingOperationId).toBe(original)
      fireEvent.click(screen.getByRole('button', { name: 'Check status' })); await flush()
      expect(h.state().pendingOperationId).toBe(original)
      expect(h.operations).toHaveLength(1)
      // A no-record answer cancelled that candidate; an explicit new edit can
      // queue behind the retained identity, but cannot bypass it.
      editSource('Another newer source'); await advance()
      terminal = true
      fireEvent.click(screen.getByRole('button', { name: 'Check status' })); await flush()
      expect(h.operations).toHaveLength(2)
      expect(h.reads.filter(url => url.startsWith('/api/operations/'))).toEqual([`/api/operations/${original}`, `/api/operations/${original}`])
    })
    it('bounds a hanging transport at the overall deadline without declaring zero charge', async () => {
      const pending = deferred<Response>()
      const h = await ready({ operation: () => pending.promise })
      editSource(); await advance()
      await advance(30000)
      expect(h.state().phase).toBe('idle')
      expect(screen.getByRole('alert')).toHaveTextContent(MESSAGE_UNKNOWN_OUTCOME)
      expect(screen.getByRole('button', { name: 'Check status' })).toBeVisible()
      await act(async () => pending.resolve(json({ translatedText: 'Late', rewrittenText: 'Late', characterCount: 46, admissionDay: USAGE.day, usage: { ...USAGE, revision: 2 } })))
      expectResult(feature, '')
    })
    it('offline edits and reconnection never dispatch until a new eligible edit', async () => {
      const h = await ready()
      vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(false)
      fireEvent(window, new Event('offline'))
      editSource(); await advance(2000)
      expect(screen.getByRole('alert')).toHaveTextContent('You’re offline.')
      vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(true)
      fireEvent(window, new Event('online')); await advance(2000)
      expect(h.operations).toHaveLength(0)
      editSource('After reconnect'); await advance()
      expect(h.operations).toHaveLength(1)
    })
    it('unknown capacity does a read and never speculatively posts', async () => {
      const usage = deferred<Response>()
      const h = await ready({ usage: () => usage.promise })
      editSource(); await advance(2000)
      expect(h.operations).toHaveLength(0)
      await act(async () => usage.resolve(json(USAGE)))
      await advance(999)
      expect(h.operations).toHaveLength(0)
      await advance(1)
      expect(h.operations).toHaveLength(1)
    })
    it('insufficient allowance blocks locally, and a status read alone cannot start processing', async () => {
      let available = 19
      const h = await ready({ usage: () => json({ ...USAGE, availableCharacters: available, revision: available }) })
      editSource('The report is ready.'); await advance(2000)
      expect(screen.getByRole('alert')).toHaveTextContent('This request needs 20 characters, but you have 19 remaining today.')
      expect(h.operations).toHaveLength(0)
      available = 100
      fireEvent.click(screen.getByRole('button', { name: 'Check availability' })); await advance(2000)
      expect(h.operations).toHaveLength(0)
      editSource('Hi.'); await advance()
      expect(h.operations).toHaveLength(1)
    })
    it('source composition suppresses stale errors while preserving the source caret', async () => {
      const pending = deferred<Response>()
      await ready({ operation: () => pending.promise })
      editSource(); await advance()
      const input = screen.getByLabelText('Source text') as HTMLTextAreaElement
      input.focus(); input.setSelectionRange(3, 3)
      fireEvent.compositionStart(input)
      await act(async () => pending.resolve(json({ category: 'processingFailure' }, 502)))
      expect(screen.queryByRole('alert')).not.toBeInTheDocument()
      expect(input).toHaveFocus()
      expect(input.selectionStart).toBe(3)
    })
    it('StrictMode mounts safely and sends only one operation', async () => {
      const h = installWorkspaceFetch()
      mountWorkspace(feature, true); await flush(); selectValid(feature)
      editSource(); await advance()
      expect(h.operations).toHaveLength(1)
      expectResult(feature, RESULT)
    })
  })
}

it('Translation retains an invalid target when source changes to the same language', async () => {
  const h = installWorkspaceFetch(); mountWorkspace('translation'); await flush()
  selectValid('translation'); editSource()
  fireEvent.change(screen.getByLabelText('Source language'), { target: { value: 'ro' } })
  await advance(2000)
  expect(screen.getByLabelText('Target language')).toHaveValue('ro')
  expect(screen.getByRole('alert')).toHaveTextContent('Choose a target language different from Romanian.')
  expect(h.operations).toHaveLength(0)
})
it('Rewriting exposes four languages and exactly nine exclusive modes', async () => {
  installWorkspaceFetch(); mountWorkspace('rewriting'); await flush()
  expect(within(screen.getByLabelText('Writing language')).getAllByRole('option')).toHaveLength(5)
  chooseMode('business')
  fireEvent.click(screen.getByRole('button', { name: 'Styles/Tones' }))
  expect(within(screen.getByRole('listbox', { name: 'Styles/Tones' })).getAllByRole('option').map(option => option.textContent?.replace('✓', ''))).toEqual(['None set', 'Simple', 'Business', 'Academic', 'Casual', 'Enthusiastic', 'Friendly', 'Confident', 'Diplomatic'])
  expect(CAPABILITIES.rewriting.defaultMode).toBe('correctionOnly')
})

it('all twelve Translation directions dispatch the exact settled selector pair', async () => {
  const h = installWorkspaceFetch(); mountWorkspace('translation'); await flush()
  const languages = ['en', 'ru', 'ro', 'zh']
  for (const source of languages) for (const target of languages) {
    if (source === target) continue
    fireEvent.change(screen.getByLabelText('Source language'), { target: { value: source } })
    fireEvent.change(screen.getByLabelText('Target language'), { target: { value: target } })
    editSource(`${source} to ${target}`)
    await advance()
    expect(h.operations.at(-1)).toMatchObject({ sourceSelection: source, target })
  }
  expect(h.operations).toHaveLength(12)
})
it('all four rewriting languages and nine exclusive modes reach the request payload', async () => {
  const h = installWorkspaceFetch(); mountWorkspace('rewriting'); await flush()
  for (const language of ['en', 'ru', 'ro', 'zh']) for (const mode of MODES) {
    fireEvent.change(screen.getByLabelText('Writing language'), { target: { value: language } })
    chooseMode(mode)
    editSource(`${language} ${mode}`)
    await advance()
    expect(h.operations.at(-1)).toMatchObject({ sourceSelection: language, mode })
  }
  expect(h.operations).toHaveLength(36)
})
it('failed capacity reads report an essential alert and read-only recovery never starts a paid request', async () => {
  let unavailable = true
  const h = installWorkspaceFetch({ usage: () => unavailable ? Promise.reject(new Error('offline')) : json(USAGE) })
  mountWorkspace('translation'); await flush(); selectValid('translation'); editSource(); await flush()
  expect(screen.getByRole('alert')).toHaveTextContent('We couldn’t check processing availability.')
  await advance(2000)
  expect(h.operations).toHaveLength(0)
  unavailable = false
  fireEvent.click(screen.getByRole('button', { name: 'Check availability' })); await advance(2000)
  expect(h.operations).toHaveLength(0)
  editSource('A new revision'); await advance()
  expect(h.operations).toHaveLength(1)
})
it.each([500, 502, 503, 504])('an unclassified HTTP %s response remains unknown and never offers a paid retry', async status => {
  const h = installWorkspaceFetch({ operation: () => json({}, status) })
  mountWorkspace('translation'); await flush(); selectValid('translation'); editSource(); await advance()
  expect(screen.getByRole('alert')).toHaveTextContent(MESSAGE_UNKNOWN_OUTCOME)
  expect(screen.queryByRole('button', { name: 'Try again' })).not.toBeInTheDocument()
  await advance(2000)
  expect(h.operations).toHaveLength(1)
})
